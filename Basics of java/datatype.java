void main(){
    //numerical Datatype
    byte num1 = 126;
    short num2 = 4999;
    int num3 = 3000000;
    long num4 = 57048723;
    System.out.println(num1);
    System.out.println(num2);
    System.out.println(num3);
    System.out.println(num4);

    //Floating DTs
    float num5 = 3.147872f;
    System.out.println(num5);
    double num6 = 4.666645345769;
    System.out.println(num6);
    
    //other datatype
    boolean abhinavIsBawee = true;
    System.out.println(abhinavIsBawee);

    char rudra = 'a';
    System.out.println(5 + rudra);
    System.out.println((char)(5 + rudra));

    //typecasting
    //Implicit
    byte value1 = 100;
    long value2 = value1;
    System.out.println(value2);
    
    //Explict
    long numm1 = 1234567897;
    int numm2 = (int)numm1 ;  
    System.out.println(numm2);
    
}
